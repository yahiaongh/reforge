"""Trusted OpenSCAD source generation.

OpenSCAD code is produced ONLY from this version-controlled template plus
numerically validated parameters. Model output, user text, or any other
untrusted string is never interpolated into the source: every substituted
value is a finite float formatted by this module, so code injection through
parameters is structurally impossible.
"""

from __future__ import annotations

from .parameters import PlateParams

#: Facet quality target: cylinder chord length <= ~0.1 mm keeps hole-diameter
#: error from segmentation far below the validation tolerance.
MIN_FN = 32
MAX_FN = 128


def format_number(value: float) -> str:
    """Format a validated finite float for safe SCAD interpolation."""
    return f"{float(value):.6f}"


def segments_for_diameter(diameter: float) -> int:
    """Deterministic $fn choice for a hole of the given diameter."""
    return max(MIN_FN, min(MAX_FN, int(diameter * 4) + MIN_FN))


def generate_scad(params: PlateParams) -> str:
    """Render editable `.scad` source for validated plate parameters."""
    lines = [
        "// Generated by Reforge from validated parameters. Editable.",
        f"// plate: {format_number(params.length)} x {format_number(params.width)}"
        f" x {format_number(params.thickness)} mm, {len(params.holes)} hole(s).",
        "difference() {",
        f"  cube([{format_number(params.length)}, {format_number(params.width)},"
        f" {format_number(params.thickness)}], center = false);",
    ]
    # Cutters extend 1 mm beyond each face to guarantee a clean through-cut.
    overhang = 1.0
    height = params.thickness + 2.0 * overhang
    for hole in params.holes:
        fn = segments_for_diameter(hole.diameter)
        lines.append(
            f"  translate([{format_number(hole.x)}, {format_number(hole.y)},"
            f" {format_number(-overhang)}])"
            f" cylinder(h = {format_number(height)},"
            f" d = {format_number(hole.diameter)}, $fn = {fn});"
        )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_scad(params: PlateParams, path: str) -> str:
    """Write generated source to *path* and return the source text."""
    source = generate_scad(params)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(source)
    return source
